export function outflowFor(name) {
  if (!name) return null
  if (OUTFLOW[name]) return OUTFLOW[name]
  const bare = name.replace(/^Lake /, '')
  if (OUTFLOW[bare]) return OUTFLOW[bare]
  const withPrefix = 'Lake ' + name
  return OUTFLOW[withPrefix] || null
}
